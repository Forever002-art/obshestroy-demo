def categories_for(token: str) -> list[str]:
    """Названия категорий, к которым относится слово запроса (например «штукатурка» → Отделочные работы)."""
    t = normalize(token)
    if len(t) < 3:
        return []
    return [CATEGORIES[i] for i, words in KEYWORDS.items()
            if any(w.startswith(t) or (len(w) >= 3 and t.startswith(w)) for w in words)]
